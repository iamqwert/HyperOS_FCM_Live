#!/usr/bin/env python3
"""Hook target inventory and OTA regression check.

Two independent sources are read, both from the repository:

* ``Hooker.kt`` -- the Group table. Its length is what the install summary's
  ``N hook(s) installed`` counts by way of ``hookE`` calls; a dropped group is
  the cheapest regression to catch before a release.
* ``FCM_HOOK_TECH_DOC.md`` §4.1 / §4.2 -- the documented method signatures with
  their target-generation column. Rows marked as removed are excluded.

``python3 scripts/check_hook_targets.py --write`` regenerates the committed
baseline ``scripts/hook_targets.json``. Plain runs compare against it.

``--dex <rom-dump dir>`` adds a symbol-level check against the local DexSQL
dataset: every documented live method is looked up with an exact ``IN (...)``
match (a LIKE match silently misses rows in this dataset). A method absent
from an OS4 dump is only an ALERT when the row claims OS4 support; OS3-only
rows are reported separately as EXPECTED, so a cross-generation miss never
reads as a broken hook.

Exit 1 means the baseline changed, the docs are unparsable, or an OS4 target
is missing from the dump.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "HyperFCMLive/src/main/java/io/github/howard20181/hyperos/fcmlive"
HOOKER = SRC / "Hooker.kt"
TECH = ROOT / "FCM_HOOK_TECH_DOC.md"
BASELINE = Path(__file__).with_name("hook_targets.json")

GROUP_RE = re.compile(r'Group\("([^"]+)",\s*"([^"]+)"\)')
SECTION_RE = re.compile(r"^###\s+(4\.\d)\b")
METHOD_RE = re.compile(r"`([A-Za-z_$][A-Za-z0-9_$]*)\s*\(")
ROW_NAME_RE = re.compile(r"^\|\s*([A-Za-z_$][A-Za-z0-9_$]*)\s*\|")
DEXSQL_CANDIDATES = (
    Path("C:/Users/Shaw/AppData/Local/DexSQL/0.1.1/dexsql.exe"),
    Path("/usr/local/bin/dexsql"),
)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def groups() -> list[dict]:
    text = read(HOOKER)
    anchors = [
        (m.start(), m.group(0)) for m in re.finditer(
            r"private fun (systemServerGroups|powerKeeperGroups)\b", text
        )
    ]
    if len(anchors) != 2:
        raise RuntimeError("expected exactly two Group tables in Hooker.kt")
    out: list[dict] = []
    for i, (start, name) in enumerate(anchors):
        end = anchors[i + 1][0] if i + 1 < len(anchors) else len(text)
        host = "powerkeeper" if "powerKeeperGroups" in name else "system_server"
        for verb, label in GROUP_RE.findall(text[start:end]):
            out.append({"host": host, "verb": verb, "name": label})
    return out


def doc_signatures() -> list[dict]:
    """Parse the §4.1/§4.2 tables; skip rows that document a removal."""
    lines = read(TECH).splitlines()
    section = ""
    out: list[dict] = []
    for line in lines:
        heading = SECTION_RE.match(line)
        if heading:
            section = heading.group(1)
            continue
        if section not in ("4.1", "4.2") or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.split("|")]
        if len(cells) < 7 or not re.fullmatch(r"[SP]\d+", cells[1]):
            continue
        removed = any("已删除（" in c or "~~" in c for c in cells)
        if removed or "非 hook" in cells[5]:
            continue
        # A signature cell can carry a parenthetical "(... 已删)" naming a
        # retired alias; it is not a live target.
        signature = re.sub(r"[（(][^）)]*已删[^）)]*[）)]", "", cells[4])
        names = sorted(set(METHOD_RE.findall(signature)))
        if not names:
            continue
        version = cells[2]
        out.append({
            "id": cells[1],
            "host": "powerkeeper" if cells[1].startswith("P") else "system_server",
            "generation": version,
            "os3": "OS3" in version,
            "os4": "OS4" in version,
            "methods": names,
        })
    if not out:
        raise RuntimeError("no signature rows parsed from the §4 tables")
    return out


def inventory() -> dict:
    g = groups()
    return {
        "note": "Generated by scripts/check_hook_targets.py. Group count is NOT "
                "the hook count in the install summary; one Group may install "
                "several hooks.",
        "groups": g,
        "signatures": doc_signatures(),
    }


def compare(current: dict, saved: dict) -> list[str]:
    old_g = {(x["host"], x["verb"], x["name"]) for x in saved.get("groups", [])}
    new_g = {(x["host"], x["verb"], x["name"]) for x in current["groups"]}
    findings = []
    for item in sorted(old_g - new_g):
        findings.append(f"group disappeared: {item[0]} / {item[1]} {item[2]}")
    for item in sorted(new_g - old_g):
        findings.append(f"group added (update baseline): {item[0]} / {item[1]} {item[2]}")
    old_s = {(x["id"], m) for x in saved.get("signatures", []) for m in x["methods"]}
    new_s = {(x["id"], m) for x in current["signatures"] for m in x["methods"]}
    for row, method in sorted(old_s - new_s):
        findings.append(f"documented target retired: {row} {method}")
    for row, method in sorted(new_s - old_s):
        findings.append(f"documented target added (update baseline): {row} {method}")
    return findings


def dexsql_binary(explicit: str | None) -> Path | None:
    if explicit:
        return Path(explicit)
    found = shutil.which("dexsql")
    if found:
        return Path(found)
    return next((p for p in DEXSQL_CANDIDATES if p.exists()), None)


def dex_inputs(dump: Path, generation: str) -> list[Path]:
    folder = dump / "OS3" if generation == "os3" else dump
    return sorted(
        p for p in folder.glob("*")
        if p.is_file()
        and p.suffix.lower() in (".jar", ".apk")
        and "-res" not in p.name
    )


def dex_hits(binary: Path, inputs: list[Path], names: list[str]) -> set[str]:
    quoted = ", ".join("'" + n.replace("'", "''") + "'" for n in sorted(names))
    sql = f"SELECT name FROM methods WHERE name IN ({quoted}) GROUP BY name"
    hits: set[str] = set()
    for path in inputs:
        result = subprocess.run(
            [str(binary), "query", f"--input={path}", f"--sql={sql}"],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            print(f"  ! {path.name}: {result.stderr.strip().splitlines()[-1:]}")
            continue
        for line in result.stdout.splitlines():
            match = ROW_NAME_RE.match(line)
            if match:
                hits.add(match.group(1))
    return hits


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="regenerate the baseline")
    ap.add_argument("--dex", type=Path, help="rom-dump directory for symbol-level check")
    ap.add_argument("--gen", choices=("os4", "os3"), default="os4")
    ap.add_argument("--dexsql", help="explicit path to the dexsql binary")
    args = ap.parse_args()

    current = inventory()
    gs = current["groups"]
    system = sum(1 for g in gs if g["host"] == "system_server")
    live = current["signatures"]
    methods = sorted({m for s in live for m in s["methods"]})
    print(f"hook targets: {len(gs)} groups (system_server {system}, "
          f"powerkeeper {len(gs) - system}), {len(live)} live rows, "
          f"{len(methods)} distinct method names")

    if args.write:
        BASELINE.write_text(
            json.dumps(current, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        print(f"baseline written: {BASELINE.relative_to(ROOT)}")
        return 0

    findings: list[str] = []
    if not BASELINE.exists():
        findings.append("baseline missing; run with --write")
    else:
        findings += compare(current, json.loads(read(BASELINE)))

    if args.dex:
        binary = dexsql_binary(args.dexsql)
        if binary is None:
            print("  ! dexsql not found; symbol-level check skipped")
        else:
            inputs = dex_inputs(args.dex, args.gen)
            print(f"dex check: {len(inputs)} input(s), generation {args.gen}")
            hits = dex_hits(binary, inputs, methods)
            expected = "os4" if args.gen == "os4" else "os3"
            alerts, cross = [], []
            for row in live:
                if not row[expected]:
                    cross.extend(row["methods"])
                    continue
                for name in row["methods"]:
                    if name not in hits:
                        alerts.append((row["id"], row["host"], name))
            print(f"  matched {len(hits)}/{len(methods)} names in the dump")
            if cross:
                print(f"  EXPECTED cross-generation ({len(cross)}): {', '.join(sorted(set(cross))[:12])}")
            if alerts:
                print(f"  ALERT, {len(alerts)} target(s) claimed {args.gen.upper()} but absent:")
                for row_id, host, name in alerts:
                    print(f"    - {row_id} [{host}] {name}")
                findings.append(f"{len(alerts)} live target(s) absent from the {args.gen} dump")

    if findings:
        print(f"hook target check: {len(findings)} finding(s)")
        for f in findings:
            print(f"  - {f}")
        return 1
    print("hook target check: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
